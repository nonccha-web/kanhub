  var host = null;

  function close() {
    host = host || document.getElementById('guideHost');
    if (host) { host.innerHTML = ''; }
    document.body.style.overflow = '';
    document.removeEventListener('keydown', onKey);
  }
  function onKey(e) {
    if (e.key === 'Escape') { close(); }
  }

